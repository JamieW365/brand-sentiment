class TestDefaults:

    def test_scraped_at_has_python_side_default(self, table):
        """scraped_at is stamped by the application, not the database."""
        col = table.columns["scraped_at"]
        assert col.default is not None
        # Python-side default only: the DB does not set this value.
        assert col.server_default is None

    def test_created_at_has_server_default(self, table):
        """created_at is set by Postgres at insert time."""
        col = table.columns["created_at"]
        assert col.server_default is not None
        assert col.default is None


class TestConstraintsAndIndexes:

    def test_unique_constraint_on_source_and_review_id(self, table):
        """The same review from the same source cannot be inserted twice."""
        uniques = [c for c in table.constraints if isinstance(c, UniqueConstraint)]
        assert len(uniques) == 1
        assert uniques[0].name == "uq_reviews_source_review_id"
        assert {col.name for col in uniques[0].columns} == {"source", "review_id"}

    def test_expected_indexes_exist(self, table):
        """Indexes that support the main query patterns are defined."""
        # table.indexes is a set of Index objects; map each name to its columns.
        indexes = {
            idx.name: [col.name for col in idx.columns] for idx in table.indexes
        }
        assert indexes == {
            "ix_reviews_source": ["source"],
            "ix_reviews_business_id": ["business_id"],
            "ix_reviews_scraped_at": ["scraped_at"],
        }


class TestInsertBehaviour:

    def test_insert_populates_generated_fields(self, session):
        """id, scraped_at and created_at are filled in without the caller supplying them."""
        review = make_review()
        session.add(review)
        session.commit()

        assert isinstance(review.id, uuid.UUID)
        assert review.scraped_at is not None
        assert review.created_at is not None

    def test_ids_are_unique_per_row(self, session):
        """Two inserted reviews never share a primary key."""
        a, b = make_review(review_id="rev-a"), make_review(review_id="rev-b")
        session.add_all([a, b])
        session.commit()

        assert a.id != b.id

    def test_scraped_at_is_stamped_fresh_per_row(self, session):
        """The default is evaluated per row, not once at class definition."""
        t1 = datetime(2026, 1, 1, 12, 0, 0, tzinfo=timezone.utc)
        t2 = datetime(2026, 1, 1, 12, 0, 1, tzinfo=timezone.utc)

        # Patch the datetime name used inside models.py so the clock is
        # deterministic. A constant default would give both rows the same value.
        with patch("shared.db.models.datetime") as mock_datetime:
            mock_datetime.now.side_effect = [t1, t2]
            a, b = make_review(review_id="rev-a"), make_review(review_id="rev-b")
            session.add_all([a, b])
            session.commit()

        # Guard against a naive timestamp sneaking in: the default must ask for UTC.
        mock_datetime.now.assert_called_with(timezone.utc)

        # SQLite drops tzinfo, so compare against the naive equivalents.
        assert a.scraped_at == t1.replace(tzinfo=None)
        assert b.scraped_at == t2.replace(tzinfo=None)

    def test_duplicate_source_and_review_id_rejected(self, session):
        """The unique constraint is enforced, not just declared."""
        session.add(make_review())
        session.commit()

        session.add(make_review())  # same source + review_id
        with pytest.raises(IntegrityError):
            session.commit()

    def test_same_review_id_allowed_across_sources(self, session):
        """Uniqueness is per source: Reddit and Yelp can reuse an ID."""
        session.add_all([
            make_review(source="yelp_api"),
            make_review(source="reddit"),
        ])
        session.commit()  # should not raise
